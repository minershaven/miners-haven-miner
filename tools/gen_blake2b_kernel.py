src=f'''/* BLAKE2b header-v2 search kernel (Bitcoin Knots Cash, Bitcoin Knots BLAKE2b), Sia stratum dialect.
   Generated by tools/gen_blake2b_kernel.py: the twelve rounds are written out with the message
   schedule fixed, so the message words stay in registers and the six zero words fold away.

   Each work item hashes one 80-byte "Sia header": prevHidden(32) | nonce(4) nonce2(4) | ntime(8) | root(32),
   BLAKE2b-256, one compression of 80 bytes. Only the low half of message word 4 (the nonce) changes,
   so the host passes the state after the three round-0 column steps that do not read word 4.
   A hash passes when its first 8 bytes, read big-endian (the top of the 256-bit number the pool
   compares), are <= target. */

#define MAX_RESULTS 31

#define ROTR32(x) as_ulong(as_uint2(x).s10)
#define ROTR24(x) rotate((ulong)(x), (ulong)40)
#define ROTR16(x) rotate((ulong)(x), (ulong)48)
#define ROTR63(x) rotate((ulong)(x), (ulong)1)

/* job[0..9]: message words (word 4 with its low half zero); job[10..25]: v0..v15 after round-0
   columns 0, 1 and 3 (column 2 entries are the initial values) */
__kernel
void blake2b_search(__constant ulong *job, uint start, ulong target, __global uint *results
#ifdef DEBUG_OUT
    , __global ulong *debug
#endif
) {{
    uint gid = get_global_id(0);
    uint nonce = start + gid;
    const ulong m0 = job[0], m1 = job[1], m2 = job[2], m3 = job[3];
    const ulong m4 = job[4] | (ulong)nonce;
    const ulong m5 = job[5], m6 = job[6], m7 = job[7], m8 = job[8], m9 = job[9];
    ulong v0 = job[10], v1 = job[11], v2 = job[12], v3 = job[13];
    ulong v4 = job[14], v5 = job[15], v6 = job[16], v7 = job[17];
    ulong v8 = job[18], v9 = job[19], v10 = job[20], v11 = job[21];
    ulong v12 = job[22], v13 = job[23], v14 = job[24], v15 = job[25];

{body}

    ulong h0 = {IV[0]} ^ 0x01010020UL ^ v0 ^ v8;
#ifdef DEBUG_OUT
    debug[gid * 4 + 0] = h0;
    debug[gid * 4 + 1] = {IV[1]} ^ v1 ^ v9;
    debug[gid * 4 + 2] = {IV[2]} ^ v2 ^ v10;
    debug[gid * 4 + 3] = {IV[3]} ^ v3 ^ v11;
#endif
    /* hash bytes 0..7 are h0 little-endian; as a big-endian number that is the byte swap */
    ulong top = as_ulong(as_uchar8(h0).s76543210);
    if (top <= target) {{
        uint k = atomic_inc(&results[0]);
        if (k < MAX_RESULTS) results[1 + k] = nonce;
    }}
}}
'''
